package lexer;

/**
 * 单词符号的种别码枚举 —— 词法分析阶段的分类核心。
 *
 * <h3>在编译器流程中的位置</h3>
 * 词法分析器（Lexer）逐字符扫描源程序，将字符序列切分为有意义的"单词"（Token），
 * 每个 Token 都必须归属到某一种别码（TokenType）。
 *
 * <h3>设计依据（编译原理教材 §3.2）</h3>
 * 根据程序设计语言的词法规则，所有单词可归为以下 9 大类：
 * <ol>
 *   <li><b>关键字</b> —— 语言保留字，有固定含义（如 int, if, while）</li>
 *   <li><b>标识符</b> —— 用户自定义名称（变量名、函数名）</li>
 *   <li><b>常量</b> —— 整数、浮点数、字符串、字符四种字面量</li>
 *   <li><b>运算符</b> —— 算术、关系、逻辑、赋值等运算符</li>
 *   <li><b>界符</b> —— 标点符号，用于分隔语句和表达式</li>
 *   <li><b>EOF</b> —— 文件结束标记，作为词法分析的终止信号</li>
 *   <li><b>UNKNOWN</b> —— 非法字符，用于词法错误恢复</li>
 * </ol>
 *
 * @author 编译原理课程设计
 * @see Token 二元式（TokenType + 属性值）
 * @see Lexer 词法分析器
 */
public enum TokenType {

    /** 关键字（保留字）—— 如 int, float, if, else, while, return 等，由 {@link Lexer#KEYWORDS} 集合判定 */
    KEYWORD,

    /** 标识符 —— 用户自定义的变量名/函数名，以字母或下划线开头，后续可含字母、数字、下划线 */
    IDENTIFIER,

    /** 整数常量 —— 纯数字序列，如 123, 0, -456（负号在语法分析阶段处理） */
    INTEGER,

    /** 浮点数常量 —— 含小数点的数字序列，如 3.14, 0.5, 1.0 */
    FLOAT,

    /** 字符串常量 —— 由双引号包围的字符序列，如 "hello world"，支持转义字符 */
    STRING,

    /** 字符常量 —— 由单引号包围的单个字符，如 'a', '\n' */
    CHAR,

    /** 运算符 —— 包含单字符运算符（+ - * / % = ! &lt; &gt;）和多字符运算符（== != &lt;= &gt;= &amp;&amp; || ++ -- += -= *= /=） */
    OPERATOR,

    /** 界符（分隔符） —— 包括圆括号 ()、花括号 {}、方括号 []、分号 ;、逗号 , 等 */
    DELIMITER,

    /** 文件结束符 —— 标志词法输入流的结束，是语法分析器判断输入结束的依据（对应 LR 分析中的 #） */
    EOF,

    /** 非法/未知字符 —— 词法错误标记，遇到无法识别的字符时产生，用于错误报告和错误恢复 */
    UNKNOWN
}
